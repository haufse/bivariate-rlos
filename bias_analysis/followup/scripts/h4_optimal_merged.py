"""h4_optimal_merged: Monte Carlo optimal b over the merged grid (full + smallb + fineb), all
models M1-M5 and n, for the Sec. 8 optimal-b table; fallback rates at b in {2,3,4} (smallb).

Ratio = min_b IMSE_K(estimator) / min_b IMSE_K(r1), paired over replications; MCSE = max of the
delta-method MCSE at the selected b's (as summarize.py) and the replication-bootstrap SE that
includes the argmin selection (B = 2000).  '*' = optimum at an end of the merged grid.
Outputs: outputs/h4_optimal_merged.csv, outputs/h4_fallback_smallb.csv,
outputs/h4_table_optimal_merged.tex (booktabs snippet, same layout as
tables/sec8-table-optimal.tex plus an oracle column), outputs/h4_output.txt.
"""
import sys

sys.dont_write_bytecode = True
import numpy as np   # noqa: E402
import pandas as pd  # noqa: E402

import common as C   # noqa: E402

ESTS = ["r1", "r2_eff", "r2_eff_bceq", "r2_or", "pot"]
NFMT = {1000: r"$10^3$", 5000: r"$5\cdot10^3$", 10000: r"$10^4$", 20000: r"$2\cdot10^4$", 100000: r"$10^5$"}


def main():
    Wb = C.boot_counts(1000)
    rows, fbr = [], []
    for mo in ("M1", "M2", "M3", "M4", "M5"):
        for n in (1000, 5000, 10000, 20000, 100000):
            specs = [(md, "main", mo, n) for md in ("full", "smallb", "fineb") if C.load(md, "main", mo, n) is not None]
            if not specs:
                continue
            df = C.load_many(specs)
            bs = np.sort(df.b.unique())
            reps, E = C.cube(df, ESTS, list(bs))
            assert len(reps) == 1000 and np.isfinite(E).all()
            ise = (E[..., C.mK] ** 2) @ C.wK
            m = ise.mean(0)
            j1 = int(np.argmin(m[:, 0]))
            bmin = np.stack([(Wb @ ise[:, :, ie]).min(1) for ie in range(len(ESTS))], 1)
            # same table restricted to the old (full) grid, for comparison
            old = np.isin(bs, C_BGRID[n])
            jo1 = int(np.flatnonzero(old)[np.argmin(m[old, 0])])
            for ie, est in enumerate(ESTS):
                j = int(np.argmin(m[:, ie]))
                rho, se = C.ratio_mcse(ise[:, j, ie], ise[:, j1, 0])
                seb = np.std(bmin[:, ie] / bmin[:, 0], ddof=1)
                jo = int(np.flatnonzero(old)[np.argmin(m[old, ie])])
                rho_old, _ = C.ratio_mcse(ise[:, jo, ie], ise[:, jo1, 0])
                rows.append(dict(model=mo, n=n, estimator=est, b_opt=bs[j], at_end=bool(j in (0, len(bs) - 1)),
                                 imse_K=m[j, ie], mcse_K=ise[:, j, ie].std(ddof=1) / np.sqrt(1000),
                                 ratio=rho, mcse=max(se, seb), b_opt_oldgrid=bs[jo], ratio_oldgrid=rho_old,
                                 grid=",".join(str(int(b)) for b in bs)))
            dg = C.load("smallb", "main", mo, n, kind="diag")
            for b, g in dg.groupby("b"):
                fbr.append(dict(exp="main", model=mo, n=n, b=b, fallback_K=g.fallback_K.mean(),
                                fallback_K10=g.fallback_K10.mean()))
    for mo in ("M1", "M2"):
        dg = C.load("smallb", "r3", mo, 10000, kind="diag")
        for b, g in dg.groupby("b"):
            fbr.append(dict(exp="r3", model=mo, n=10000, b=b, fallback_K=g.fallback_K.mean(),
                            fallback_K10=g.fallback_K10.mean()))
    df = pd.DataFrame(rows)
    C.save(df, "h4_optimal_merged.csv")
    fb = pd.DataFrame(fbr)
    C.save(fb, "h4_fallback_smallb.csv")
    pd.set_option("display.width", 220)
    piv = df.pivot_table(index=["model", "n"], columns="estimator", values=["b_opt", "ratio", "mcse", "b_opt_oldgrid", "ratio_oldgrid"])
    out = [piv.round(3).to_string(), "", "r1 10^4 IMSE at optimum:",
           df[df.estimator == "r1"][["model", "n", "b_opt", "imse_K", "mcse_K"]].assign(
               imse_K=lambda x: 1e4 * x.imse_K, mcse_K=lambda x: 1e4 * x.mcse_K).round(4).to_string(index=False),
           "", "fallback (share) at b in {2,3,4}:", fb.round(4).to_string(index=False)]
    txt = "\n".join(out)
    print(txt)
    (C.OUT / "h4_output.txt").write_text(txt + "\n")
    # LaTeX snippet (M1-M4, as the Sec. 8 table, plus oracle column)
    L = [r"% generated by bias_analysis/followup/scripts/h4_optimal_merged.py",
         r"% merged grid full+smallb+fineb (outputs/h4_optimal_merged.csv) -- cross-check for sec8_simulations/figures.py",
         r"\begingroup\small\setlength{\tabcolsep}{3.5pt}",
         r"\begin{tabular}{llrcrcrcrcrc}", r"\toprule",
         r"& & \multicolumn{2}{c}{$r=1$} & \multicolumn{2}{c}{$r=2$, $\hat\Sigma_n^{-1}$}"
         r" & \multicolumn{2}{c}{$r=2$, $\hat\Sigma_n^{-1}$, corrected} & \multicolumn{2}{c}{$r=2$, $\Sigma^{-1}$}"
         r" & \multicolumn{2}{c}{POT}\\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}\cmidrule(lr){9-10}\cmidrule(lr){11-12}",
         r"Model & $n$ & $b^\dagger$ & $10^4\,\mathrm{IMSE}_K$ & $b^\dagger$ & ratio & $b^\dagger$ & ratio"
         r" & $b^\dagger$ & ratio & $b^\dagger$ & ratio\\", r"\midrule"]
    for mo in ("M1", "M2", "M3", "M4"):
        first = True
        for n in (1000, 5000, 10000, 20000, 100000):
            x = df[(df.model == mo) & (df.n == n)].set_index("estimator")
            if x.empty:
                continue
            bstr = lambda e: f"{int(x.loc[e, 'b_opt'])}" + (r"$^{\ast}$" if x.loc[e, "at_end"] else "")
            cells = [f"({mo})" if first else "", NFMT[n], bstr("r1"),
                     f"{1e4 * x.loc['r1', 'imse_K']:.3f} ({1e4 * x.loc['r1', 'mcse_K']:.3f})"]
            for e in ("r2_eff", "r2_eff_bceq", "r2_or", "pot"):
                cells += [bstr(e), f"{x.loc[e, 'ratio']:.2f} ({x.loc[e, 'mcse']:.2f})"]
            L.append(" & ".join(cells) + r"\\")
            first = False
        L.append(r"\addlinespace[2pt]" if mo != "M4" else r"\bottomrule")
    L += [r"\end{tabular}\endgroup"]
    (C.OUT / "h4_table_optimal_merged.tex").write_text("\n".join(L) + "\n")
    print("wrote", C.OUT / "h4_table_optimal_merged.tex")


C_BGRID = {1000: [5, 10, 20, 40], 5000: [5, 10, 20, 40, 80], 10000: [5, 10, 20, 40, 80, 160],
           20000: [5, 10, 20, 40, 80, 160, 320], 100000: [10, 20, 40, 80, 160, 320]}

if __name__ == "__main__":
    main()
